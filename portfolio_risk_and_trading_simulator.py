#part 4
ma_3_day_list = []
ma_7_day_list = []
for i in range(0, len(prices) - 2):
  ma_3_day_list.append(np.average(prices[i:i+3]))
for i in range(0, len(prices) - 6):
  ma_7_day_list.append(np.average(prices[i:i+7]))
ma_3_day = np.array(ma_3_day_list, dtype=np.float16)
ma_7_day = np.array(ma_7_day_list, dtype=np.float16)


ma_3_day_aligned = ma_3_day[-len(ma_7_day):]
signals_list = []

for i in range(0, len(ma_7_day)):
  if ma_3_day_aligned[i] > ma_7_day[i]:
    signals_list.append(1)
  else:
    signals_list.append(0)

signals = np.array(signals_list)

print(signals)

# part 5
print(len(signals))
print(len(percentage_return))

returns_aligned = percentage_return[-len(signals):]
print(returns_aligned)
strategy_returns = returns_aligned * signals
print(strategy_returns)

#part 6
position_changes_list = []
position_changes_list.append(signals[0])
for i in range(1, len(signals)):
  if signals[i - 1] == signals[i]:
    position_changes_list.append(0)
  else:
    position_changes_list.append(1)
position_changes = np.array(position_changes_list)
print(position_changes)

#part 7
portfolio_list = []

for i in range(0, len(strategy_returns)):
  if position_changes[i] == 1:
    if i == 0:
      price = initial_capital - initial_capital * 0.001
      portfolio_list.append(price * (strategy_returns[i] / 100)+ price)
    else:
      price = portfolio_list[i - 1] - portfolio_list[i - 1] * 0.001
      portfolio_list.append(price * (strategy_returns[i] / 100)+ price)
  if position_changes[i] == 0:
    if i == 0:
      price = prices[i]
      portfolio_list.append(price * (strategy_returns[i] / 100)+ price)
    else:
      price = portfolio_list[i - 1]
      portfolio_list.append(price * (strategy_returns[i] / 100)+ price)



portfolio = np.array(portfolio_list)
print(portfolio)