import numpy as np

prices = np.array([
    100, 102, 101, 105, 107,
    106, 110, 112, 111, 115,
    117, 116, 120, 119, 123,
    125, 124, 128, 130, 129
])
initial_capital = 10_000

#part 2
percentage_return_list = []
for i in range(1, len(prices)):
  percentage_return_list.append(((100 * prices[i])/prices[i - 1])-100)
percentage_return = np.array(percentage_return_list)


print(percentage_return)

#part 3
votality = np.std(percentage_return)

print(votality)
